CREATE TABLE IF NOT EXISTS word_changes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  word_id TEXT COLLATE "C" NOT NULL REFERENCES words(id),
  field TEXT COLLATE "C" NOT NULL,
  old TEXT COLLATE "C",
  new TEXT COLLATE "C",
  why TEXT COLLATE "C",
  source TEXT COLLATE "C" NOT NULL DEFAULT 'review',
  applied BIGINT NOT NULL DEFAULT 1,
  reverted_at TEXT COLLATE "C",
  at TEXT COLLATE "C" NOT NULL
);
CREATE INDEX IF NOT EXISTS word_changes_at ON word_changes(at);
CREATE INDEX IF NOT EXISTS word_changes_word_field ON word_changes(word_id, field);

CREATE TABLE IF NOT EXISTS word_reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  word_id TEXT COLLATE "C" NOT NULL REFERENCES words(id),
  kind TEXT COLLATE "C" NOT NULL,
  note TEXT COLLATE "C",
  created_at TEXT COLLATE "C" NOT NULL,
  closed_at TEXT COLLATE "C"
);
CREATE INDEX IF NOT EXISTS word_reports_open ON word_reports(closed_at, created_at);

CREATE TABLE IF NOT EXISTS word_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  text TEXT COLLATE "C" NOT NULL,
  url TEXT COLLATE "C",
  created_at TEXT COLLATE "C" NOT NULL,
  status TEXT COLLATE "C" NOT NULL DEFAULT 'queued',
  word_id TEXT COLLATE "C",
  note TEXT COLLATE "C"
);
CREATE INDEX IF NOT EXISTS word_requests_status ON word_requests(status, created_at);

CREATE TABLE IF NOT EXISTS news_days (
  day TEXT COLLATE "C" NOT NULL,
  key TEXT COLLATE "C" NOT NULL,
  n BIGINT NOT NULL,
  url TEXT COLLATE "C",
  PRIMARY KEY (day, key)
);
CREATE INDEX IF NOT EXISTS news_days_key ON news_days(key, day);

CREATE TABLE IF NOT EXISTS word_skips (
  key TEXT COLLATE "C" PRIMARY KEY,
  reason TEXT COLLATE "C",
  at TEXT COLLATE "C" NOT NULL
);

CREATE TABLE IF NOT EXISTS day_plans (
  day TEXT COLLATE "C" PRIMARY KEY,
  fresh TEXT COLLATE "C" NOT NULL,
  extra BIGINT NOT NULL DEFAULT 0,
  created_at TEXT COLLATE "C" NOT NULL
);

CREATE TABLE IF NOT EXISTS practice (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mode TEXT COLLATE "C" NOT NULL,
  word_id TEXT COLLATE "C" NOT NULL REFERENCES words(id),
  correct BIGINT NOT NULL,
  at TEXT COLLATE "C" NOT NULL
);
CREATE INDEX IF NOT EXISTS practice_word_at ON practice(word_id, at);
CREATE INDEX IF NOT EXISTS practice_at ON practice(at);

