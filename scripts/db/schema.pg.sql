-- Postgres(Supabase, 스키마 worty) 스키마 — migrations/0001~0011(D1/SQLite)을 모두 반영한 지금 모양을 한 파일로 옮긴 것.
-- 적용: worty_app 으로 붙어(검색 경로 = worty) `node scripts/db/d1-to-pg.mjs --schema` (몇 번 돌려도 안전, IF NOT EXISTS).
-- 고칠 때는 migrations/ 에 D1 마이그레이션을 더하고 여기에도 같은 변경을 더한다(되돌리기 길인 D1 과 모양을 맞춘다).
--
-- 옮긴 규칙
--  - TEXT 는 전부 COLLATE "C": 데이터베이스 기본(en_US.UTF-8)은 기호를 건너뛰고 비교해 SQLite(BINARY) 와 정렬·비교가 달라진다.
--    "C" 에서는 lower()·ILIKE 도 ASCII 만 바꿔 SQLite 의 lower()·LIKE 와 같다.
--  - INTEGER 는 BIGINT(SQLite 정수는 64비트 — words.seq 는 80억까지 간다). worker/db.ts 가 읽을 때 Number 로 돌린다.
--  - REAL → DOUBLE PRECISION, AUTOINCREMENT → IDENTITY(BY DEFAULT: 이관 때 id 를 그대로 넣고 d1-to-pg.mjs 가 시퀀스를 맞춘다).
--  - datetime('now') 기본값 → 같은 꼴('YYYY-MM-DD HH:MM:SS', UTC) 글자.
--  - read_budget(0010)은 D1 읽기 지킴이 전용이라 옮기지 않는다(pg 에서는 지킴이를 끈다).

CREATE TABLE IF NOT EXISTS words (
  id TEXT COLLATE "C" PRIMARY KEY,
  lemma TEXT COLLATE "C" NOT NULL,
  pos TEXT COLLATE "C" NOT NULL,
  gender TEXT COLLATE "C",
  plural TEXT COLLATE "C",
  ipa TEXT COLLATE "C",
  level TEXT COLLATE "C" NOT NULL,
  level_src TEXT COLLATE "C" NOT NULL,
  gloss_en TEXT COLLATE "C",
  gloss_ko TEXT COLLATE "C",
  gloss_status TEXT COLLATE "C" NOT NULL DEFAULT 'missing',
  example_de TEXT COLLATE "C",
  example_ko TEXT COLLATE "C",
  example_src TEXT COLLATE "C",
  scene_en TEXT COLLATE "C",
  image_id TEXT COLLATE "C",
  image_status TEXT COLLATE "C" NOT NULL DEFAULT 'none',
  freq_rank BIGINT,
  seq BIGINT NOT NULL,
  created_at TEXT COLLATE "C" NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
  checked_at TEXT COLLATE "C",
  news_rank BIGINT,
  news_hits30 BIGINT NOT NULL DEFAULT 0,
  pinned BIGINT NOT NULL DEFAULT 0,
  example_hit TEXT COLLATE "C"
);
CREATE UNIQUE INDEX IF NOT EXISTS words_lemma_pos ON words(lemma, pos);
CREATE INDEX IF NOT EXISTS words_seq ON words(seq);
CREATE INDEX IF NOT EXISTS words_checked_at ON words(checked_at);
CREATE INDEX IF NOT EXISTS words_level ON words(level);
CREATE INDEX IF NOT EXISTS words_image_none ON words(seq) WHERE image_status = 'none';
CREATE INDEX IF NOT EXISTS words_text_gap ON words(seq) WHERE gloss_ko IS NULL OR example_de IS NULL OR scene_en IS NULL;
CREATE INDEX IF NOT EXISTS words_image_ok ON words(seq) WHERE image_status = 'ok';

CREATE TABLE IF NOT EXISTS cards (
  word_id TEXT COLLATE "C" PRIMARY KEY REFERENCES words(id),
  state BIGINT NOT NULL DEFAULT 0,
  due TEXT COLLATE "C" NOT NULL,
  stability DOUBLE PRECISION NOT NULL DEFAULT 0,
  difficulty DOUBLE PRECISION NOT NULL DEFAULT 0,
  elapsed_days BIGINT NOT NULL DEFAULT 0,
  scheduled_days BIGINT NOT NULL DEFAULT 0,
  learning_steps BIGINT NOT NULL DEFAULT 0,
  reps BIGINT NOT NULL DEFAULT 0,
  lapses BIGINT NOT NULL DEFAULT 0,
  last_review TEXT COLLATE "C",
  introduced_at TEXT COLLATE "C",
  suspended BIGINT NOT NULL DEFAULT 0,
  suspended_at TEXT COLLATE "C"
);
CREATE INDEX IF NOT EXISTS cards_due ON cards(due);
CREATE INDEX IF NOT EXISTS cards_state_due ON cards(state, due);
CREATE INDEX IF NOT EXISTS cards_introduced ON cards(introduced_at);
CREATE INDEX IF NOT EXISTS cards_suspended_at ON cards(suspended_at) WHERE suspended = 1;
CREATE INDEX IF NOT EXISTS cards_state ON cards(state);

CREATE TABLE IF NOT EXISTS reviews (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  word_id TEXT COLLATE "C" NOT NULL REFERENCES words(id),
  rating BIGINT NOT NULL,
  reviewed_at TEXT COLLATE "C" NOT NULL,
  elapsed_days BIGINT NOT NULL DEFAULT 0,
  scheduled_days BIGINT NOT NULL DEFAULT 0,
  session_id TEXT COLLATE "C",
  undone BIGINT NOT NULL DEFAULT 0,
  prev_json TEXT COLLATE "C"
);
CREATE INDEX IF NOT EXISTS reviews_word_time ON reviews(word_id, reviewed_at);
CREATE INDEX IF NOT EXISTS reviews_time ON reviews(reviewed_at);

CREATE TABLE IF NOT EXISTS notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  kind TEXT COLLATE "C" NOT NULL,
  day TEXT COLLATE "C" NOT NULL,
  scheduled_at TEXT COLLATE "C" NOT NULL,
  sent_at TEXT COLLATE "C",
  status TEXT COLLATE "C" NOT NULL DEFAULT 'queued',
  payload_json TEXT COLLATE "C" NOT NULL,
  discord_message_id TEXT COLLATE "C",
  error TEXT COLLATE "C",
  action_key TEXT COLLATE "C",
  opened_at TEXT COLLATE "C"
);
CREATE UNIQUE INDEX IF NOT EXISTS notifications_kind_day ON notifications(kind, day);
CREATE INDEX IF NOT EXISTS notifications_scheduled ON notifications(scheduled_at);

CREATE TABLE IF NOT EXISTS settings (
  key TEXT COLLATE "C" PRIMARY KEY,
  value TEXT COLLATE "C" NOT NULL,
  updated_at TEXT COLLATE "C" NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS')
);
